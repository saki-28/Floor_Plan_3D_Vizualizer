"""Packs the training code into one script for a Kaggle notebook (Kaggle runs a single code file) and writes its settings.

    python3 -I training/kaggle/build.py [--out training/kaggle/build] [--minutes 95] [--steps 24000] [-- extra train.py args]
    kaggle kernels push -p training/kaggle/build -t 9000

The notebook is private, runs on Kaggle's 2× T4 with the CubiCasa5k dataset attached, draws the
labels, trains with one process per GPU and leaves model_best.pt, log.txt, test_results.json and
pred_test/ (class maps of the 400 test plans) in its output. Fetch them with
    kaggle kernels output <owner>/floorplan3d-wall-model -p data/models/<run>
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TRAINING = os.path.dirname(HERE)

RUNNER = r'''
import os, subprocess, sys, time
import torch

CODE = '/tmp/fp3d'
os.makedirs(CODE, exist_ok=True)
for name, source in SOURCES.items():
    with open(os.path.join(CODE, name), 'w') as f:
        f.write(source)
sys.path.insert(0, CODE)
from cubicasa import prepare_labels

root = next(d for d, _, files in os.walk('/kaggle/input') if 'train.txt' in files)
labels = '/tmp/labels'
t = time.time()
made = prepare_labels(root, labels)
open(os.path.join(labels, '.done'), 'w').close()
print(f'data at {root}; labels drawn for {made} plans in {time.time() - t:.0f} s', flush=True)

gpus = max(1, torch.cuda.device_count())
cmd = [sys.executable, '-u', '-m', 'torch.distributed.run', '--standalone', f'--nproc_per_node={gpus}', os.path.join(CODE, 'train.py'),
       '--data', root, '--labels', labels, '--out', '/kaggle/working', *TRAIN_ARGS]
print(' '.join(cmd), flush=True)
subprocess.run(cmd, check=True)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(HERE, 'build'))
    ap.add_argument('--slug', default='floorplan3d-wall-model')
    ap.add_argument('--owner', default='jeswintobias')
    ap.add_argument('--minutes', default='95')
    ap.add_argument('--steps', default='24000')
    ap.add_argument('extra', nargs='*', help='more train.py arguments, after --')
    args = ap.parse_args()

    sources = {}
    for name in ('cubicasa.py', 'model.py', 'train.py'):
        with open(os.path.join(TRAINING, name)) as f:
            sources[name] = f.read()
    train_args = ['--minutes', args.minutes, '--steps', args.steps, *args.extra]
    script = (
        '"""FloorPlan3D wall model training on CubiCasa5k (generated by training/kaggle/build.py; edit the sources there)."""\n'
        f'SOURCES = {sources!r}\nTRAIN_ARGS = {train_args!r}\n{RUNNER}'
    )
    os.makedirs(args.out, exist_ok=True)
    code_file = 'fp3d_wall_model.py'
    with open(os.path.join(args.out, code_file), 'w') as f:
        f.write(script)
    meta = {
        'id': f'{args.owner}/{args.slug}',
        'title': 'FloorPlan3D wall model',
        'code_file': code_file,
        'language': 'python',
        'kernel_type': 'script',
        'is_private': True,
        'enable_gpu': True,
        'enable_tpu': False,
        'enable_internet': False,
        'machine_shape': 'NvidiaTeslaT4',
        'dataset_sources': ['qmarva/cubicasa5k'],
        'competition_sources': [],
        'kernel_sources': [],
        'model_sources': [],
    }
    with open(os.path.join(args.out, 'kernel-metadata.json'), 'w') as f:
        json.dump(meta, f, indent=2)
    print(f'{args.out}/{code_file} ({len(script) / 1000:.0f} kB), train args {train_args}')


if __name__ == '__main__':
    main()
